public enum TransactionType {
    HOLD,      // заморозка монет заказчика
    TRANSFER,  // окончательное списание у заказчика и начисление исполнителю
    REFUND,    // возврат замороженных монет заказчику
    BONUS      // бонусное начисление (регистрация, навыки и т.д.)
}
